#!/usr/bin/env node
/**
 * Embeds the built web app (apps/web/dist, without source maps) into a TypeScript module the
 * staging Worker can serve directly. Used where Cloudflare's separate static-asset upload is not
 * available (the asset upload API authenticates with its own short-lived token in the
 * Authorization header). Output: src/generated/webAssets.ts (git-ignored).
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "..", "web", "dist");
const out = join(root, "src", "generated", "webAssets.ts");

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".webmanifest": "application/manifest+json",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const entries = walk(dist)
  .filter((p) => !p.endsWith(".map"))
  .map((p) => {
    const path = `/${relative(dist, p).split("\\").join("/")}`;
    const type = TYPES[extname(p)] ?? "application/octet-stream";
    return { path, type, body: readFileSync(p).toString("base64") };
  });

if (!entries.some((e) => e.path === "/index.html")) {
  throw new Error(`index.html not found in ${dist}; build the web app first`);
}

const lines = entries.map(
  (e) =>
    `  ${JSON.stringify(e.path)}: { type: ${JSON.stringify(e.type)}, body: ${JSON.stringify(e.body)} },`,
);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/embed-web.mjs. Do not edit or commit.\nexport const webAssets: Record<string, { type: string; body: string }> = {\n${lines.join("\n")}\n};\n`,
);
const kb = Math.round(entries.reduce((n, e) => n + e.body.length, 0) / 1024);
console.log(`Embedded ${entries.length} files (${kb} KiB base64) into ${relative(root, out)}`);
